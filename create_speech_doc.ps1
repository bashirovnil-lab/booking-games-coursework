$word = $null
$doc = $null

function Set-ParagraphBaseFormat {
  param([Parameter(Mandatory)] $Paragraph)
  $Paragraph.Range.Font.Name = 'Times New Roman'
  $Paragraph.Range.Font.Size = 14
  $Paragraph.Format.Alignment = 3
  $Paragraph.Format.FirstLineIndent = 35.4
  $Paragraph.Format.LineSpacingRule = 1
  $Paragraph.Format.LineSpacing = 18
  $Paragraph.Format.SpaceBefore = 0
  $Paragraph.Format.SpaceAfter = 0
}

try {
  $word = New-Object -ComObject Word.Application
  $word.Visible = $false
  $word.DisplayAlerts = 0
  $doc = $word.Documents.Add()

  $section = $doc.Sections.Item(1)
  $section.PageSetup.TopMargin = 56.7
  $section.PageSetup.BottomMargin = 56.7
  $section.PageSetup.LeftMargin = 85.05
  $section.PageSetup.RightMargin = 42.525

  $selection = $word.Selection
  $selection.Font.Name = 'Times New Roman'
  $selection.Font.Size = 14
  $selection.ParagraphFormat.Alignment = 1
  $selection.ParagraphFormat.LineSpacingRule = 1
  $selection.ParagraphFormat.LineSpacing = 18
  $selection.ParagraphFormat.SpaceBefore = 0
  $selection.ParagraphFormat.SpaceAfter = 0

  $selection.Font.Bold = $true
  $selection.TypeText('ТЕКСТ ВЫСТУПЛЕНИЯ К ПРЕЗЕНТАЦИИ')
  $selection.TypeParagraph()
  $selection.Font.Bold = $false
  $selection.TypeText('по проекту «Сайт бронирования кабинок, консолей и выдачи игр»')
  $selection.TypeParagraph()
  $selection.TypeParagraph()

  foreach ($slide in $slides) {
    $selection.Font.Name = 'Times New Roman'
    $selection.Font.Size = 14
    $selection.Font.Bold = $true
    $selection.ParagraphFormat.Alignment = 1
    $selection.ParagraphFormat.FirstLineIndent = 0
    $selection.TypeText($slide.Title)
    $selection.TypeParagraph()

    $selection.Font.Bold = $false
    $selection.ParagraphFormat.Alignment = 3
    $selection.ParagraphFormat.FirstLineIndent = 35.4

    $paragraphs = ($slide.Text -split "`r?`n") | Where-Object { $_.Trim().Length -gt 0 }
    foreach ($line in $paragraphs) {
      $selection.TypeText($line.Trim())
      $selection.TypeParagraph()
    }
    $selection.TypeParagraph()
  }

  foreach ($p in $doc.Paragraphs) {
    $text = ($p.Range.Text -replace '[\r\a]', '').Trim()
    if ($text.Length -eq 0) {
      $p.Format.FirstLineIndent = 0
      $p.Format.SpaceBefore = 0
      $p.Format.SpaceAfter = 0
      continue
    }
    $p.Range.Font.Name = 'Times New Roman'
    $p.Range.Font.Size = 14
    $p.Format.LineSpacingRule = 1
    $p.Format.LineSpacing = 18
    $p.Format.SpaceBefore = 0
    $p.Format.SpaceAfter = 0
  }

  if (Test-Path -LiteralPath $outPath) {
    $backup = Join-Path $outDir ("Текст_выступления_к_презентации_backup_{0}.docx" -f (Get-Date -Format 'yyyyMMdd_HHmmss'))
    Copy-Item -LiteralPath $outPath -Destination $backup
  }

  $doc.SaveAs2($outPath, 16)
  $doc.Close($true) | Out-Null
  $word.Quit() | Out-Null
  [System.Runtime.InteropServices.Marshal]::ReleaseComObject($word) | Out-Null
  Write-Output "Создан файл: $outPath"
}
catch {
  if ($doc -ne $null) { $doc.Close($false) | Out-Null }
  if ($word -ne $null) { $word.Quit() | Out-Null; [System.Runtime.InteropServices.Marshal]::ReleaseComObject($word) | Out-Null }
  throw
}
